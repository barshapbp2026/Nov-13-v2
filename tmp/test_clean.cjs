  s = s.replace(/ााँ/g, 'ाँ').replace(/ाा/g, 'ा').replace(/ीी/g, 'ी').replace(/ेे/g, 'े').replace(/ोो/g, 'ो');
  // Fix stray spaces before vowel signs / halanta
  s = s.replace(/\s+([\u0901-\u0903\u093E-\u094D])/g, '$1');
  // Fix split years like "२० ३४", "२० ५५", "२० ७७"
