const isOcrPdf = (pdfName = '') => ocrPdfKeywords.some(k => pdfName.includes(k));

// Build clean Nepali legal vocabulary
const vocab = new Map();
const addWord = (w, weight = 10) => {
  if (!w || !/^[\u0900-\u0963\u0970-\u097F]{1,22}$/.test(w)) return;
  vocab.set(w, (vocab.get(w) || 0) + weight);
};
const addCleanWords = (text, weight = 1) => {
  if (!text) return;
  text.split(/[\s.,;:()\[\]"“”'‘’\-–—\/०-९0-9।]+/).forEach(w => {
    if (/^[\u0900-\u0963\u0970-\u097F]{2,20}$/.test(w)) {
      addWord(w, weight);
    }
  });
};

constData.forEach(c => {
  addCleanWords(c.title_name, 30);
  addCleanWords(c.anusuchi_title, 30);
});

rows.forEach(r => {
  if (isOcrPdf(r.pdf_name)) return; // Only learn vocab from clean-Unicode PDFs!
  const s = (r.title_name || '') + ' ' + (r.anusuchi_title || '');
  if (!/[\u0915-\u0939]\u094D\s+[\u0915-\u0939]/.test(s) && !/[\u0900-\u0963]{17,}/.test(s)) {
    addCleanWords(r.title_name, 4);
    addCleanWords(r.anusuchi_title, 4);
  }
});

