function fixSpacesAndVibhaktis(str) {
  let s = str;
  for (let pass = 0; pass < 3; pass++) {
    const parts = s.split(/(\s+)/);
    for (let i = 0; i < parts.length - 2; i += 2) {
      const w1 = parts[i];
      const sp = parts[i + 1];
      const w2 = parts[i + 2];
      if (!w1 || !w2 || !sp || !/^\s+$/.test(sp)) continue;

      const c1 = w1.replace(/^[(\["“‘]+|[.,;:)\]"”’\-–—]+$/g, '');
      const c2 = w2.replace(/^[(\["“‘]+|[.,;:)\]"”’\-–—]+$/g, '');
      if (!/^[\u0900-\u0963\u0970-\u097F]+$/.test(c1) || !/^[\u0900-\u0963\u0970-\u097F]+$/.test(c2)) continue;

      const w1EndsVib = /(को|का|की|मा|ले|लाई|बाट|देखि)$/.test(c1);

      // 1. Vibhakti stuck to start of w2: "मोही लाईनिष्कासन" -> "मोहीलाई निष्कासन"
      const vibMatch = c2.match(/^(को|का|की|मा|ले|लाई|बाट|देखि)([\u0900-\u0963\u0970-\u097F]{2,})$/);
      if (vibMatch && !vocab.has(c2) && !w1EndsVib && w1 === c1 && (vocab.has(c1) || vocab.has(vibMatch[2]) || vocab.has(c1 + vibMatch[1]))) {
        parts[i] = w1 + vibMatch[1];
        parts[i + 2] = w2.slice(vibMatch[1].length);
        continue;
      }

      // 2. Standalone detached vibhakti: "कर्मचारी ले" -> "कर्मचारीले" (wait: only if w1 doesn't end in vibhakti and w1 is >=2 chars)
      if (/^(को|का|की|मा|ले|लाई|बाट|देखि)$/.test(c2) && c1.length >= 2 && !w1EndsVib && w1 === c1) {
        parts[i] = w1 + w2;
        parts[i + 1] = '';
        parts[i + 2] = '';
        continue;
      }

      // 3. Broken word split across space: merge ONLY if w1+w2 IS in vocab AND !(vocab.has(c1) && vocab.has(c2))
      if (vocab.has(c1 + c2) && !(vocab.has(c1) && vocab.has(c2)) && w1 === c1) {
        parts[i] = w1 + w2;
        parts[i + 1] = '';
        parts[i + 2] = '';
        continue;
      }

      // 4. Tiny non-word fragment on either side
      if (((c1.length <= 2 && !validShortWords.has(c1) && !vocab.has(c1)) || (c2.length <= 2 && !validShortWords.has(c2) && !vocab.has(c2))) && w1 === c1 && !w1EndsVib) {
        parts[i] = w1 + w2;
        parts[i + 1] = '';
        parts[i + 2] = '';
        continue;
      }
    }
    s = parts.join('').replace(/\s+/g, ' ').trim();
  }

  // Digits glued to Nepali words (avoid breaking ८क / २९क / १ख)
  s = s.replace(/([०-९]+)([\u0900-\u0963]{2,})/g, (m, nums, word) => {
    const subMatch = word.match(/^([कखगघङचछजझ])(को|का|की|मा|ले|लाई|बाट|देखि)$/);
    if (subMatch) return `${nums}${subMatch[1]} ${subMatch[2]}`;
    return `${nums} ${word}`;
  });
  s = s.replace(/([\u0900-\u0963]{2,})([०-९]+)/g, '$1 $2');
  return s.replace(/\s+/g, ' ').trim();
}

function segmentRun(token) {
  if (vocab.has(token) || token.length <= 10) return token;
  const n = token.length;
  const dp = new Array(n + 1).fill(-Infinity);
  const back = new Array(n + 1).fill(0);
  dp[0] = 0;

  for (let i = 1; i <= n; i++) {
    for (let j = Math.max(0, i - 18); j < i; j++) {
      if (dp[j] === -Infinity) continue;
      if (j > 0 && token[j - 1] === '\u094D' && !standaloneHalanta.has(token.slice(Math.max(0, j - 6), j))) continue;
      const sub = token.slice(j, i);
      if (/^[\u0901-\u0903\u093E-\u094D]/.test(sub)) continue;
      let score;
      if (vocab.has(sub)) {
        score = dp[j] + (sub.length * sub.length) * 2.2 + Math.min(vocab.get(sub), 60) * 0.25;
      } else {
        score = dp[j] - (sub.length <= 2 ? 75 : sub.length * 5 + 18);
      }
      if (score > dp[i]) {
        dp[i] = score;
        back[i] = j;
      }
    }
  }

  const parts = [];
  let cur = n;
  while (cur > 0) {
    const prev = back[cur];
    parts.push(token.slice(prev, cur));
    cur = prev;
  }
  parts.reverse();

  const merged = [];
  for (let i = 0; i < parts.length; i++) {
    const p = parts[i];
    if (p.length === 1 && !validShortWords.has(p) && merged.length > 0) {
      merged[merged.length - 1] += p;
    } else {
      merged.push(p);
    }
  }
  return merged.join(' ');
}

function cleanText(str, pdfName = '') {
  if (!str) return '';
  let s = applyCommonClean(str);
  if (isOcrPdf(pdfName)) s = applyHeavyOcrClean(s);
  s = fixSpacesAndVibhaktis(s);
  s = s.replace(/[\u0900-\u0963\u0970-\u097F]{11,}/g, token => segmentRun(token));
  // Re-run vibhakti/fragment cleanup once after segmentation
  s = fixSpacesAndVibhaktis(s);
  s = s.replace(/\(\s+/g, '(').replace(/\s+\)/g, ')').replace(/\s+,/g, ',').replace(/\s+:/g, ':');
  s = s.replace(/\s+/g, ' ').trim();
  return s;
}

